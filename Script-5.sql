DROP TABLE IF EXISTS ORDER_ITEMS, ORDERS, PRODUCTS, CUSTOMERS CASCADE;

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID  INTEGER PRIMARY KEY,
    FULL_NAME    TEXT NOT NULL,
    CITY         TEXT NOT NULL,
    CHANNEL      TEXT NOT NULL,
    SIGNUP_DATE  DATE NOT NULL
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID   INTEGER PRIMARY KEY,
    PRODUCT_NAME TEXT NOT NULL,
    CATEGORY     TEXT NOT NULL,
    UNIT_COST    NUMERIC(10,2) NOT NULL,
    LIST_PRICE   NUMERIC(10,2) NOT NULL
);

CREATE TABLE ORDERS (
    ORDER_ID       INTEGER PRIMARY KEY,
    CUSTOMER_ID    INTEGER NOT NULL REFERENCES CUSTOMERS (CUSTOMER_ID),
    ORDER_DATE     DATE NOT NULL,
    STATUS         TEXT NOT NULL,
    PAYMENT_METHOD TEXT NOT NULL
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID INTEGER PRIMARY KEY,
    ORDER_ID      INTEGER NOT NULL REFERENCES ORDERS (ORDER_ID),
    PRODUCT_ID    INTEGER NOT NULL REFERENCES PRODUCTS (PRODUCT_ID),
    QUANTITY      INTEGER NOT NULL,
    UNIT_PRICE    NUMERIC(10,2) NOT NULL,
    DISCOUNT_RATE NUMERIC(4,2) NOT NULL
);
----COUNTING ROWS
SELECT 'CUSTOMERS' AS TABLE_NAME, COUNT(*) FROM CUSTOMERS
UNION ALL SELECT 'PRODUCTS',    COUNT(*) FROM PRODUCTS
UNION ALL SELECT 'ORDERS',      COUNT(*) FROM ORDERS
UNION ALL SELECT 'ORDER_ITEMS', COUNT(*) FROM ORDER_ITEMS;

----CHECKING FIRST AND LAST DATES
SELECT (SELECT MIN(ORDER_DATE)  FROM ORDERS)    AS FIRST_ORDER,
       (SELECT MAX(ORDER_DATE)  FROM ORDERS)    AS LAST_ORDER,
       (SELECT MIN(SIGNUP_DATE) FROM CUSTOMERS) AS FIRST_SIGNUP,
       (SELECT MAX(SIGNUP_DATE) FROM CUSTOMERS) AS LAST_SIGNUP;

----JOINING ORDERS,CUSTOMERS AND PRODUCTS TABLES
CREATE OR REPLACE VIEW SALES_LINES AS
SELECT O.ORDER_ID, O.CUSTOMER_ID, O.ORDER_DATE, O.STATUS, O.PAYMENT_METHOD,
       I.ORDER_ITEM_ID, I.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY,
       I.QUANTITY, I.UNIT_PRICE, I.DISCOUNT_RATE, P.UNIT_COST,
       I.QUANTITY * I.UNIT_PRICE * (1 - I.DISCOUNT_RATE)                 AS REVENUE,
       I.QUANTITY * (I.UNIT_PRICE * (1 - I.DISCOUNT_RATE) - P.UNIT_COST) AS GROSS_PROFIT
FROM ORDERS O
JOIN ORDER_ITEMS I ON I.ORDER_ID   = O.ORDER_ID
JOIN PRODUCTS    P ON P.PRODUCT_ID = I.PRODUCT_ID;
SELECT *FROM SALES_LINES;


SELECT EXTRACT(YEAR FROM ORDER_DATE)::INT                     AS YEAR,
       COUNT(DISTINCT ORDER_ID)                               AS ORDERS,
       ROUND(SUM(REVENUE))                                    AS REVENUE,
       ROUND(SUM(GROSS_PROFIT))                               AS GROSS_PROFIT,
       ROUND(100 * SUM(GROSS_PROFIT) / SUM(REVENUE), 1)       AS MARGIN_PCT,
       ROUND(SUM(REVENUE) / COUNT(DISTINCT ORDER_ID))         AS AOV
FROM SALES_LINES
WHERE STATUS = 'COMPLETED'
GROUP BY 1
ORDER BY 1;

----BUSINESS GROWTH PER YEAR
WITH Y AS (
    SELECT EXTRACT(YEAR FROM ORDER_DATE)::INT AS YEAR,
           COUNT(DISTINCT ORDER_ID) AS ORDERS,
           SUM(REVENUE) AS REVENUE
    FROM SALES_LINES
    WHERE STATUS = 'COMPLETED'
    GROUP BY 1
)
SELECT YEAR,
       ROUND(REVENUE) AS REVENUE,
       ROUND(100.0 * (REVENUE / LAG(REVENUE) OVER (ORDER BY YEAR) - 1), 1)          AS REVENUE_GROWTH_PCT,
       ROUND(100.0 * (ORDERS::NUMERIC / LAG(ORDERS) OVER (ORDER BY YEAR) - 1), 1)   AS ORDER_GROWTH_PCT
FROM Y
ORDER BY YEAR;

----COMPARING BUSINESS PERFORMANCE PER MONTH
WITH M AS (
    SELECT DATE_TRUNC('MONTH', ORDER_DATE)::DATE AS MONTH_START,
           SUM(REVENUE) AS REVENUE
    FROM SALES_LINES
    WHERE STATUS = 'COMPLETED'
    GROUP BY 1
)
SELECT TO_CHAR(MONTH_START, 'MON YYYY') AS MONTH,
       ROUND(REVENUE) AS REVENUE,
       ROUND(100.0 * (REVENUE / LAG(REVENUE)     OVER (ORDER BY MONTH_START) - 1), 1) AS MOM_PCT,
       ROUND(100.0 * (REVENUE / LAG(REVENUE, 12) OVER (ORDER BY MONTH_START) - 1), 1) AS YOY_PCT,
       ROUND(AVG(REVENUE) OVER (ORDER BY MONTH_START ROWS BETWEEN 2 PRECEDING AND CURRENT ROW)) AS AVG_3M
FROM M
ORDER BY MONTH_START;

----
SELECT CATEGORY,
       ROUND(SUM(REVENUE))                                                   AS REVENUE,
       ROUND(100.0 * SUM(REVENUE)      / SUM(SUM(REVENUE))      OVER (), 1)  AS REVENUE_SHARE_PCT,
       ROUND(SUM(GROSS_PROFIT))                                              AS GROSS_PROFIT,
       ROUND(100.0 * SUM(GROSS_PROFIT) / SUM(SUM(GROSS_PROFIT)) OVER (), 1)  AS PROFIT_SHARE_PCT,
       ROUND(100.0 * SUM(GROSS_PROFIT) / SUM(REVENUE), 1)                    AS MARGIN_PCT
FROM SALES_LINES
WHERE STATUS = 'COMPLETED'
GROUP BY CATEGORY
ORDER BY REVENUE DESC;

----PERFORMANCE PER CITY
SELECT
	C.CITY,
	COUNT(DISTINCT C.CUSTOMER_ID) AS CUSTOMERS,
	ROUND(SUM(S.REVENUE)) AS REVENUE,
	ROUND(100.0 * SUM(S.REVENUE) / SUM(SUM(S.REVENUE)) OVER (), 1) AS REVENUE_SHARE_PCT,
	ROUND(SUM(S.REVENUE) / COUNT(DISTINCT C.CUSTOMER_ID)) AS REVENUE_PER_CUSTOMER,
	ROUND(SUM(S.REVENUE) / COUNT(DISTINCT S.ORDER_ID)) AS AOV
FROM
	CUSTOMERS C
LEFT JOIN SALES_LINES S
       ON
	S.CUSTOMER_ID = C.CUSTOMER_ID
	AND S.STATUS = 'COMPLETED'
GROUP BY
	C.CITY
ORDER BY
	REVENUE_PER_CUSTOMER DESC;

